export const EXERCISES = Object.fromEntries(LIST.map((e) => [e.id, e]));
export const LIBRARY = LIST;

// A workout exercise built from a library entry.
export function fromLibrary(id, d, extra = {}) {
  const { dose: def, group, equipment, ...ex } = structuredClone(EXERCISES[id]);
  return { ...ex, ...(d ?? def), superset: null, ...extra };
}
